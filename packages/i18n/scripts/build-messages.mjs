// ARC-043 — interface texts live in messages/{locale}/{namespace}.json; keys are ui.{namespace}.{path} (07-design/03 § 2).
// Generates src/messages.generated.ts: the flat dictionary per locale and the MessageKey union (unknown keys fail to compile).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const locales = readdirSync(resolve(root, 'messages'));
const flat = {};
for (const locale of locales) {
  const dir = resolve(root, 'messages', locale);
  const out = {};
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const ns = file.replace(/\.json$/, '');
    const walk = (node, prefix) => {
      for (const [k, v] of Object.entries(node)) {
        // "_" holds the value of a node that also has children (ui.common.search and ui.common.search.recent).
        const key = k === '_' ? prefix : `${prefix}.${k}`;
        if (typeof v === 'string') out[key] = v;
        else walk(v, key);
      }
    };
    walk(JSON.parse(readFileSync(resolve(dir, file), 'utf8')), `ui.${ns}`);
  }
  flat[locale] = out;
}
const keys = Object.keys(flat.fr).sort();
const src =
  `// Generated by scripts/build-messages.mjs — do not edit. Source: messages/*/*.json\n` +
  `export const messages = ${JSON.stringify(flat, null, 2)} as const;\n\n` +
  `export type Locale = keyof typeof messages;\n` +
  `export type MessageKey =\n${keys.map((k) => `  | '${k}'`).join('\n')};\n`;
writeFileSync(resolve(root, 'src/messages.generated.ts'), src);
console.log(`${keys.length} keys (${locales.join(', ')}).`);
