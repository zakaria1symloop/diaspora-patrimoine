// DSN-040 — icon set generated from the Figma export (Design/assets/icons). Run: pnpm --filter @dp/ui icons
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../../Design/assets/icons');
const out = resolve(here, '../src/icons/icons.generated.ts');
const entries = [];
for (const file of readdirSync(src).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(resolve(src, file), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24';
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  entries.push(`  '${file.replace('.svg', '')}': { viewBox: '${viewBox}', body: ${JSON.stringify(inner)} },`);
}
writeFileSync(
  out,
  `// Generated by scripts/build-icons.mjs from Design/assets/icons — do not edit.\n` +
    `export const icons = {\n${entries.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof icons;\n`,
);
console.log(`${entries.length} icons written.`);
