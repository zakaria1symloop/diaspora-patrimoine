// Completeness of a property (CAL-050, CAL-051) and of a dossier (CAL-055).

export type PropertyType = 'APARTMENT' | 'STUDIO' | 'DUPLEX' | 'VILLA' | 'LAND' | 'COMMERCIAL';
export type DeliveryStatus = 'ON_PLAN' | 'UNDER_CONSTRUCTION' | 'DELIVERED';

/** Plain facts about a property, gathered by the caller (media counts already resolved per kind). */
export interface PropertyCompletenessInput {
  title: string | null;
  type: PropertyType | null;
  rooms: number | null;
  surface: number | string | null;
  /** At least one lot with a price. */
  hasPricedLot: boolean;
  regionId: string | null;
  developerId: string | null;
  deliveryStatus: DeliveryStatus | null;
  deliveryDate: string | null;
  /** `PHOTO` + `RENDER_3D` media of the property itself. */
  photoCount: number;
  /** Same for its program (used when the property has none, MOD-236). */
  programPhotoCount: number;
  /** A `PLAN` on the property or one of its lots. */
  hasPlan: boolean;
  /** A `PLAN` on its program (fallback, MOD-236). */
  programHasPlan: boolean;
  /** `PANO_360` views. */
  panoCount: number;
  descriptionLength: number;
  descriptionAutoGenerated: boolean;
  featureCount: number;
  /** The property or its program has coordinates. */
  hasCoordinates: boolean;
  poiCount: number;
}

export interface CompletenessFeatures {
  /** `features.tour360` */
  tour360: boolean;
  /** `features.poi` */
  poi: boolean;
}

export type MandatoryField = 'TITLE' | 'TYPE' | 'ROOMS' | 'SURFACE' | 'PRICE' | 'REGION' | 'DEVELOPER' | 'DELIVERY';

export type CompletenessActionCode =
  | `FIELD_${MandatoryField}`
  | 'ADD_PHOTOS'
  | 'ADD_PLAN'
  | 'ADD_TOUR_360'
  | 'COMPLETE_DESCRIPTION'
  | 'ADD_FEATURES'
  | 'ADD_COORDINATES'
  | 'ADD_POIS';

/** CAL-051 — an action proposed next to the score. */
export interface CompletenessAction {
  code: CompletenessActionCode;
  /** Points gained on the 0–100 score. */
  gain: number;
  mandatory: boolean;
  /** Number of items to add (photos, features, POIs), when meaningful. */
  count?: number;
}

export interface PropertyCompleteness {
  score: number;
  points: number;
  possiblePoints: number;
  missingMandatory: MandatoryField[];
  /** `catalogue.publishMinScore` reached. */
  publishable: boolean;
  /** `catalogue.completeScore` reached. */
  complete: boolean;
  actions: CompletenessAction[];
}

/** CAL-050 — photo points: 1 → 8 · 2 → 10 · 3 → 12 · 4 → 14 · 5 → 16 · 6 and more → 20. */
export function photoPoints(count: number): number {
  if (count <= 0) return 0;
  if (count >= 6) return 20;
  return 6 + 2 * count;
}

const DESCRIPTION_MIN = 300;
const FEATURES_MIN = 5;
const POI_MIN = 3;

function missingMandatoryFields(p: PropertyCompletenessInput): MandatoryField[] {
  const missing: MandatoryField[] = [];
  if (!p.title || p.title.trim() === '') missing.push('TITLE');
  if (!p.type) missing.push('TYPE');
  const roomsNotNeeded = p.type === 'LAND' || p.type === 'COMMERCIAL';
  if (!roomsNotNeeded && (p.rooms === null || p.rooms <= 0)) missing.push('ROOMS');
  if (p.surface === null || Number(p.surface) <= 0) missing.push('SURFACE');
  if (!p.hasPricedLot) missing.push('PRICE');
  if (!p.regionId) missing.push('REGION');
  if (!p.developerId) missing.push('DEVELOPER');
  if (!p.deliveryStatus || (p.deliveryStatus !== 'DELIVERED' && !p.deliveryDate)) missing.push('DELIVERY');
  return missing;
}

/**
 * CAL-050 — property completeness score, 0 to 100: 8 mandatory fields × 5 · photos 20 · plan 10 · 360° tour 10 ·
 * description ≥ 300 characters, not generated 8 · ≥ 5 features 6 · location 3 + 3. When `features.tour360` /
 * `features.poi` are off, their points leave the calculation and the score is brought back to 100:
 * round(100 × obtained ÷ possible). Thresholds: publishable ≥ `publishMinScore` (60), complete ≥ `completeScore` (85).
 * CAL-051 — actions sorted by decreasing gain, missing mandatory fields first; disabled features are not proposed.
 */
export function propertyCompleteness(
  p: PropertyCompletenessInput,
  features: CompletenessFeatures = { tour360: true, poi: true },
  thresholds: { publishMinScore: number; completeScore: number } = { publishMinScore: 60, completeScore: 85 },
): PropertyCompleteness {
  const missingMandatory = missingMandatoryFields(p);
  const effectivePhotos = p.photoCount > 0 ? p.photoCount : p.programPhotoCount;
  const parts = {
    mandatory: (8 - missingMandatory.length) * 5,
    photos: photoPoints(effectivePhotos),
    plan: p.hasPlan || p.programHasPlan ? 10 : 0,
    tour: features.tour360 && p.panoCount >= 1 ? 10 : 0,
    description: p.descriptionLength >= DESCRIPTION_MIN && !p.descriptionAutoGenerated ? 8 : 0,
    features: p.featureCount >= FEATURES_MIN ? 6 : 0,
    coordinates: p.hasCoordinates ? 3 : 0,
    pois: features.poi && p.poiCount >= POI_MIN ? 3 : 0,
  };
  const possiblePoints = 100 - (features.tour360 ? 0 : 10) - (features.poi ? 0 : 3);
  const points = Object.values(parts).reduce((s, v) => s + v, 0);
  const toScore = (pts: number): number => Math.floor((200 * pts + possiblePoints) / (2 * possiblePoints)); // round half up of 100 × pts ÷ possible
  const score = toScore(points);
  const gain = (extra: number): number => toScore(points + extra) - score;

  const actions: CompletenessAction[] = missingMandatory.map((f) => ({ code: `FIELD_${f}` as const, gain: gain(5), mandatory: true }));
  const optional: CompletenessAction[] = [];
  if (parts.photos < 20) optional.push({ code: 'ADD_PHOTOS', gain: gain(20 - parts.photos), mandatory: false, count: 6 - p.photoCount });
  if (parts.plan === 0) optional.push({ code: 'ADD_PLAN', gain: gain(10), mandatory: false });
  if (features.tour360 && parts.tour === 0) optional.push({ code: 'ADD_TOUR_360', gain: gain(10), mandatory: false });
  if (parts.description === 0) optional.push({ code: 'COMPLETE_DESCRIPTION', gain: gain(8), mandatory: false });
  if (parts.features === 0) optional.push({ code: 'ADD_FEATURES', gain: gain(6), mandatory: false, count: FEATURES_MIN - p.featureCount });
  if (parts.coordinates === 0) optional.push({ code: 'ADD_COORDINATES', gain: gain(3), mandatory: false });
  if (features.poi && parts.pois === 0) optional.push({ code: 'ADD_POIS', gain: gain(3), mandatory: false, count: POI_MIN - p.poiCount });
  optional.sort((a, b) => b.gain - a.gain);

  return {
    score,
    points,
    possiblePoints,
    missingMandatory,
    publishable: score >= thresholds.publishMinScore,
    complete: score >= thresholds.completeScore,
    actions: [...actions, ...optional],
  };
}

