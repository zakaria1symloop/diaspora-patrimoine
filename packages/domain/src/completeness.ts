// CAL-055 — dossier completeness

export type DocumentStatus = 'PENDING' | 'RECEIVED' | 'VALIDATED' | 'REJECTED' | 'EXPIRED' | 'WAIVED';
export type DocumentSource = 'CHECKLIST' | 'AD_HOC' | 'BANK_REQUEST';

/** A `DossierDocument`, reduced to what CAL-055 needs. */
export interface DossierDocumentFacts {
  isRequired: boolean;
  status: DocumentStatus;
  source: DocumentSource;
  /** Comes from a bank list (`BANK_FILE`): counted per submission, not here (CYC-161). */
  fromBankList?: boolean;
  /** Internal piece (MOD § 3.3): never counted. */
  isInternal?: boolean;
  /** Belongs to a removed borrower (`DossierParty.removedAt`). */
  partyRemoved?: boolean;
}

/**
 * CAL-055 — required = required pieces of the client list and added by hand, excluding removed borrowers (and bank
 * pieces, internal pieces); satisfied = those `VALIDATED` or `WAIVED` (`EXPIRED` is not satisfied);
 * completenessPct = integer part of 100 × satisfied ÷ required, 100 without required piece. 8 / 12 → 66.
 */
export function dossierCompleteness(documents: readonly DossierDocumentFacts[]): {
  required: number;
  satisfied: number;
  completenessPct: number;
} {
  const required = documents.filter(
    (d) => d.isRequired && !d.partyRemoved && !d.isInternal && !d.fromBankList && d.source !== 'BANK_REQUEST',
  );
  const satisfied = required.filter((d) => d.status === 'VALIDATED' || d.status === 'WAIVED').length;
  return {
    required: required.length,
    satisfied,
    completenessPct: required.length === 0 ? 100 : Math.floor((100 * satisfied) / required.length),
  };
}
