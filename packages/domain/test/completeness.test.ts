import { describe, expect, test } from 'vitest';
import { dossierCompleteness, photoPoints, propertyCompleteness, type DossierDocumentFacts, type PropertyCompletenessInput } from '../src/index.js';

// The 8 mandatory fields filled, nothing else.
const MANDATORY_ONLY: PropertyCompletenessInput = {
  title: 'Appartement T3 – Résidence El Yasmine', type: 'APARTMENT', rooms: 3, surface: '85', hasPricedLot: true, regionId: 'ALG',
  developerId: 'bahia', deliveryStatus: 'UNDER_CONSTRUCTION', deliveryDate: '2027-10-01',
  photoCount: 0, programPhotoCount: 0, hasPlan: false, programHasPlan: false, panoCount: 0, descriptionLength: 120,
  descriptionAutoGenerated: false, featureCount: 2, hasCoordinates: false, poiCount: 0,
};
const BOTH_OFF = { tour360: false, poi: false };

describe('CAL-050 property completeness', () => {
  test('CAL-050 example (both features off, 87 possible points): 8 fields + 3 photos = 52 points → 60, publishable', () => {
    const r = propertyCompleteness({ ...MANDATORY_ONLY, photoCount: 3 }, BOTH_OFF);
    expect([r.points, r.possiblePoints, r.score, r.publishable]).toEqual([52, 87, 60, true]);
  });

  test('CAL-050 example: 8 fields + 1 photo = 48 points → 55, not yet publishable', () => {
    const r = propertyCompleteness({ ...MANDATORY_ONLY, photoCount: 1 }, BOTH_OFF);
    expect([r.points, r.score, r.publishable]).toEqual([48, 55, false]);
  });

  test('CAL-050 photo scale: 1 → 8 · 2 → 10 · 3 → 12 · 4 → 14 · 5 → 16 · 6+ → 20', () => {
    expect([0, 1, 2, 3, 4, 5, 6, 9].map(photoPoints)).toEqual([0, 8, 10, 12, 14, 16, 20, 20]);
  });

  test('CAL-050 a complete property scores 100 (≥ 85: complete)', () => {
    const r = propertyCompleteness({
      ...MANDATORY_ONLY, photoCount: 6, hasPlan: true, panoCount: 1, descriptionLength: 300, featureCount: 5, hasCoordinates: true, poiCount: 3,
    });
    expect([r.score, r.complete, r.actions]).toEqual([100, true, []]);
  });

  test('CAL-050 rooms counted automatically for land and commercial premises; delivery date required unless delivered', () => {
    expect(propertyCompleteness({ ...MANDATORY_ONLY, type: 'LAND', rooms: null }).missingMandatory).toEqual([]);
    expect(propertyCompleteness({ ...MANDATORY_ONLY, rooms: null }).missingMandatory).toEqual(['ROOMS']);
    expect(propertyCompleteness({ ...MANDATORY_ONLY, deliveryDate: null }).missingMandatory).toEqual(['DELIVERY']);
    expect(propertyCompleteness({ ...MANDATORY_ONLY, deliveryStatus: 'DELIVERED', deliveryDate: null }).missingMandatory).toEqual([]);
  });

  test('CAL-050 program photos and plan used when the property has none (MOD-236)', () => {
    const r = propertyCompleteness({ ...MANDATORY_ONLY, programPhotoCount: 4, programHasPlan: true });
    expect(r.points).toBe(40 + 14 + 10);
    expect(propertyCompleteness({ ...MANDATORY_ONLY, photoCount: 1, programPhotoCount: 6 }).points).toBe(48);
  });

  test('CAL-050 description: 300 characters, not auto-generated; location 3 + 3', () => {
    expect(propertyCompleteness({ ...MANDATORY_ONLY, descriptionLength: 299 }).points).toBe(40);
    expect(propertyCompleteness({ ...MANDATORY_ONLY, descriptionLength: 300 }).points).toBe(48);
    expect(propertyCompleteness({ ...MANDATORY_ONLY, descriptionLength: 500, descriptionAutoGenerated: true }).points).toBe(40);
    expect(propertyCompleteness({ ...MANDATORY_ONLY, hasCoordinates: true, poiCount: 3 }).points).toBe(46);
    expect(propertyCompleteness({ ...MANDATORY_ONLY, hasCoordinates: true, poiCount: 3 }, BOTH_OFF).points).toBe(43);
  });
});

describe('CAL-051 completeness actions', () => {
  test('CAL-051 sorted by decreasing gain: « Ajouter 5 photos (+12) », plan (+10), 360° tour (+10)…', () => {
    const r = propertyCompleteness({ ...MANDATORY_ONLY, photoCount: 1 });
    expect(r.actions.slice(0, 3)).toEqual([
      { code: 'ADD_PHOTOS', gain: 12, mandatory: false, count: 5 },
      { code: 'ADD_PLAN', gain: 10, mandatory: false },
      { code: 'ADD_TOUR_360', gain: 10, mandatory: false },
    ]);
    expect(r.actions.map((a) => a.code)).toEqual(['ADD_PHOTOS', 'ADD_PLAN', 'ADD_TOUR_360', 'COMPLETE_DESCRIPTION', 'ADD_FEATURES', 'ADD_COORDINATES', 'ADD_POIS']);
  });

  test('CAL-051 missing mandatory fields first, marked mandatory; disabled features not proposed', () => {
    const r = propertyCompleteness({ ...MANDATORY_ONLY, title: '', photoCount: 6 }, BOTH_OFF);
    expect(r.actions[0]).toEqual({ code: 'FIELD_TITLE', gain: 6, mandatory: true }); // 5 points on 87 → +6 on the score
    expect(r.actions.some((a) => a.code === 'ADD_TOUR_360' || a.code === 'ADD_POIS')).toBe(false);
  });
});

describe('CAL-055 dossier completeness', () => {
  const doc = (status: DossierDocumentFacts['status'], extra: Partial<DossierDocumentFacts> = {}): DossierDocumentFacts => ({
    isRequired: true, status, source: 'CHECKLIST', ...extra,
  });

  test('CAL-055 example: 8 satisfied out of 12 → 66 %', () => {
    const docs = [...Array(6).fill(doc('VALIDATED')), doc('WAIVED'), doc('WAIVED'), doc('PENDING'), doc('RECEIVED'), doc('REJECTED'), doc('EXPIRED')];
    expect(dossierCompleteness(docs)).toEqual({ required: 12, satisfied: 8, completenessPct: 66 });
  });

  test('CAL-055 no required piece → 100; EXPIRED not satisfied', () => {
    expect(dossierCompleteness([doc('PENDING', { isRequired: false })])).toEqual({ required: 0, satisfied: 0, completenessPct: 100 });
    expect(dossierCompleteness([doc('EXPIRED')]).completenessPct).toBe(0);
  });

  test('CAL-055 removed borrowers, bank pieces and internal pieces are not counted; ad-hoc pieces are', () => {
    const docs = [
      doc('VALIDATED'),
      doc('PENDING', { source: 'AD_HOC' }),
      doc('PENDING', { partyRemoved: true }),
      doc('PENDING', { source: 'BANK_REQUEST' }),
      doc('PENDING', { fromBankList: true }),
      doc('PENDING', { isInternal: true }),
    ];
    expect(dossierCompleteness(docs)).toEqual({ required: 2, satisfied: 1, completenessPct: 50 });
  });
});
